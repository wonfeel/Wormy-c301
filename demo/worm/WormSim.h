    // убивает AC-усиление") - АБСОЛЮТНЫЙ (не dorsal-minus-ventral) avgState()
    // дорсальной и вентральной групп мотонейронов по каждой позиции, снятый
    // в ТОЙ ЖЕ точке step(), что и debugRawMotorVoltage() (тот же
    // m_dorsalByPos/m_ventralByPos, net.state(id), т.е. ДО muscle_calcium_
    // фильтра). debugRawMotorVoltage()/debugRawCurvature() смотрят только на
    // РАЗНОСТЬ (d-v) - она нечувствительна к тому, дрейфует ли d и v вместе
    // (общий, common-mode уровень). Здесь - раздельные d и v, чтобы отдельно
    // проверить: не уезжает ли их средний (DC) уровень от activationTheta
    // так, что sigmoid((V-activationTheta)/activationSlope) садится на
    // пологий участок и локальный наклон sigmoid'(V) падает, снижая
    // эффективное AC-усиление всей петли (net -> muscle -> body ->
    // proprioception -> net) независимо от какой-либо leak/capacitance
    // постоянной времени. Чисто аддитивно: ничего не читает эти два вектора,
    // только заполняет для offline-анализа (см. tests/worm_v2_measurement).
    void debugRawDorsalVentralState(std::vector<float>& outDorsal, std::vector<float>& outVentral) const {
        outDorsal = m_lastRawDorsalState;
        outVentral = m_lastRawVentralState;
    }

