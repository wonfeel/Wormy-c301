    // проект уже словил один реальный баг от неконтролируемого глобального
    // RNG state в этой же сессии - не повторять). Ничего не делает сама по
    // себе, если не вызвана явно - чисто аддитивный opt-in хук, ноль влияния
    // на обычный step() (см. tests/worm_v2_measurement's trace-режим,
