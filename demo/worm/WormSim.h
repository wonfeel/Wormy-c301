        // tau_V=20мс -> leak=1/tau_V=50).
        std::atomic<float> muscleLeakScale{50.0f};

        // Утечка ОТДЕЛЬНО для мотонейронов (DA/DB/DD/VA/VB/VD) - см.
        // Network::set_motor_leak_scale. v1: найдено необходимым при
        // калибровке CPG (теперь удалён) - даже с ненулевым muscleLeakScale,
        // впрыснутый CPG-сигнал не доходил до измеримой частоты, потому что
        // сами мотонейроны используют общий leakScale (дефолт 1.0, полоса
        // пропускания ~0.16Гц) и сглаживали сигнал ещё до мышц.
        //
