        //
        // ПЕРЕСМОТРЕНО (0.1 -> 0.05, см. WORM_V5_REAL_AMPLITUDE_CALIBRATION.md,
        // одновременно с muscleLeakScale/bodyPoseDecayRate ниже - полная
        // история и честный компромисс задокументированы у bodyPoseDecayRate,
        // не дублируется здесь). 0.05с - честный БЫСТРЫЙ край того же
        // цитируемого диапазона Butler et al. 2015 (0.05-0.50с), не выход за
        // его пределы - выбран, чтобы частично компенсировать замедление
        // самовозбуждения от muscleLeakScale=25 (см. закрытую-форму DDE/Hopf
        // логику раздела 2 того файла), не наугад подобранное число.
        // ВОЗВРАТ К 0.1 (WORM_V5_SPATIAL_ENVELOPE_DIAGNOSIS.md): 0.05 -
        // быстрый край цитируемого Butler et al. 2015 диапазона (0.05-0.50с) -
        // был выбран в V5 не по прямому измерению, а по неподтверждённому
        // рассуждению про сдвиг частоты Хопф-бифуркации задержкой, и служил
        // компенсацией той же ошибки позиционирования мотонейронов, что и
        // muscleLeakScale выше. На исправленной конфигурации выигрыша не даёт.
        // 0.1 остаётся внутри того же цитируемого диапазона.
        // 0.1 -> 0.05 (WORM_V5_SPATIAL_ENVELOPE_DIAGNOSIS.md раздел 14).
        // ЭТО ВТОРОЙ РАЗВОРОТ этого значения за сессию, и стоит сказать прямо
        // почему. Сначала 0.1 -> 0.05 по рассуждению про сдвиг частоты
        // Хопф-бифуркации - рассуждение не было проверено, значение откачено
        // назад к 0.1. Теперь 0.1 -> 0.05 снова, но уже по прямому замеру на
        // со-масштабированной точке (decay=3/gain=1200), 16 баз x 4 сида:
        // частота 0.1201 -> 0.1256 Гц, скорость 0.0631 -> 0.0659 BL/s,
