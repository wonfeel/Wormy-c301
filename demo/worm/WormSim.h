        // ВОЗВРАТ К 50.0 (WORM_V5_SPATIAL_ENVELOPE_DIAGNOSIS.md): 25.0 было
        // найдено перебором в V5 ради роста амплитуды изгиба - но, как
        // выяснилось, оно компенсировало ОШИБКУ в позиционировании
