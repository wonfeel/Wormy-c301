        // обоснованной осью (мотонейроны - реальный отдельный класс с
        // собственной, отдельно калибруемой утечкой) - оставлен как есть,
        // дефолт 1.0 не тронут. ВНИМАНИЕ: это МНОЖИТЕЛЬ, не гейн - 1.0
        // означает "не менять", НЕ "выключено" (0.0 здесь означало бы убрать
        // утечку мотонейронов совсем - реальное, большое изменение, не
        // нейтральное).
