        // ось и скорость затухания позы тела должны свипаться СОВМЕСТНО, не
        // по отдельности.
        //
        // ПЕРЕСМОТРЕНО (50 -> 25, см. WORM_V5_MUSCLE_LEAK_RESULTS.md и
