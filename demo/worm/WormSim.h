        // цитируемого Butler et al. 2015 диапазона 0.05-0.50с, на его быстром
        // краю. Ниже 0.05 смысла нет: 0.03 даёт ПОБИТОВО те же числа, что
        // 0.05 - tau сравнялся с шагом dt=0.05 и перестал быть фильтром.
        std::atomic<float> muscleCalciumTau{0.05f};

        // ДОФАМИН-ПОДОБНОЕ АДАПТИВНОЕ СОСТОЯНИЕ - см. WormSim::
        // applyDopamineDrive за полным обоснованием. ВТОРОЕ (после cpgGain)
        // сознательное исключение из "поведение только из настоящей сети" в
        // этом проекте - добавлено по прямому запросу пользователя после
        // того, как ПЯТЬ независимых осей "искать одну фиксированную
        // константу, одинаково хорошую на обе среды" (DVA-механосенсация,
        // локальная механосенсация, лик/ёмкость по классам, синапс-знак,
        // проприоцепция - см. WORM.md раздел 6) провалились одинаково.
        // Реальная биология (Vidal-Gadea et al. 2011, PNAS 108:17504):
        // настоящий червь переключает походку НЕ только непрерывной
        // проприоцепцией - контакт с субстратом активирует дофаминергические
        // ADE/PDE нейроны (через D1-подобные рецепторы), которые продвигают
        // crawl-режим; это категорически другой РЫЧАГ, чем всё испробованное
        // раньше - не константа, найденная поиском на обе среды сразу, а
        // СОСТОЯНИЕ, которое само медленно подстраивается под РЕАЛЬНО
        // посчитанную нагрузку (тот же normalizedLoad, что уже питает
        // DVA/mechanoGain/CPG), с постоянной времени на порядки медленнее
        // быстрой синаптической передачи (реальные нейромодуляторы
        // диффундируют внесинаптически и действуют секунды-минуты, не
        // миллисекунды) - что этот проект НИКОГДА не пробовал: все пять
        // проваленных осей были либо мгновенными (проприоцепция/
        // механосенсация каждый шаг), либо фиксированными на весь прогон
        // (лик/ёмкость/синапс-знак).
        std::atomic<float> dopamineGain{0.0f};  // сила реального сигнала в ADEL/ADER/PDEL/PDER (только связность/визуализация - не участвует в вычислении эффекта ниже, честности ради см. applyDopamineDrive). 0.0 = выключено
