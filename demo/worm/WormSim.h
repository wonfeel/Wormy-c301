        // (CPG) уже не существует.
        //   dCa_i/dt = (V_i - Ca_i) / tau_Ca,   tau_Ca = 0.1s (было 0.3s)
        // Обоснование диапазона: Butler, Branicky, Yemini, Liewald,
        // Gottschalk, Kerr, Chklovskii, Schafer 2015 (J. R. Soc. Interface
        // 12:20140963, PMC4277086) - оптимизированные постоянные времени
        // активации мышцы: 0.05с (быстрая)/0.50с (медленная), peak-to-max
        // 0.13с. ИСПРАВЛЕНО (было ошибочно указано "0.1-0.5с" - неточная
        // перефразировка первоисточника, поймано независимой проверкой
        // агентом при шиповании 0.1, честный нижний край диапазона - 0.05с,
        // не 0.1с, см. WORM_V2_RESULTS.md за полным разбором расхождения).
        // 0.3с (v2 исходный дефолт) был компромиссом ближе к медленному концу
        // диапазона, не к быстрому, как ошибочно утверждал предыдущий
        // комментарий.
        //
        // ПЕРЕСМОТРЕНО (см. WORM_V2_RESULTS.md, раздел "Диагностика частоты
        // после шиповки v2"): прямая трассировка/своп по этому параметру (не
        // поиск) показала, что 0.3с - ВНУТРИ замкнутой проприоцептивной петли
        // - заметно подавляет собственную частоту самовозбуждения сети (0.3с
        // -> ~0.14Гц; tau->0 -> ~0.38Гц, близко к линейному потолку 0.32Гц
        // из анализа собственных чисел сети, tests/worm_network_eigenmodes).
        // 0.1с - НЕ буквально нижняя граница цитаты (та - 0.05с), но
        // комфортно внутри неё, честно, без выхода за диапазон - даёт
        // ~0.22-0.32Гц в зависимости от bodyPoseDecayRate (см. ниже), не
        // ~0.14Гц. muscle_output(id) (существующий код, WormSim менять не
        // пришлось) автоматически начинает возвращать Ca_i вместо V_i, как
