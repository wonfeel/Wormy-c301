        // рождённую ВЫШЕ по потоку (в самой сети под навязанным CPG-темпом).
        //
        // V2 (см. WORM_V2_DESIGN.md раздел 2.2b): включена как БОЕВОЙ
        // параметр, ВМЕСТЕ с реальной ненулевой muscleLeakScale (см. ниже),
        // не по одной, как в v1 - тот старый отрицательный результат
        // диагностировал несогласованность выше по потоку (сети под
