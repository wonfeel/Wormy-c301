        std::atomic<float> muscleTargetTau{0.1f};

        // WormBody::joint_soft_saturation_ (see body.hpp::
        // set_joint_soft_saturation, body.cpp WormBody::step) -
        // WORM_V5_JOINT_CLAMP_RESULTS.md found that raising jointAngleClamp
        // above does NOT let the stationary mid-body band settle below the
        // ceiling - it just pins against whatever new ceiling is set, at
        // exactly zero variance across every tested value (0.25/0.35/0.5/
        // 0.6). Per the project owner's own proposal ("shouldn't we remove
        // the max-angle constraint, or make it so the body resists turning
        // instead of strictly limiting it?"), this toggle replaces the
        // DISCONTINUOUS std::clamp with a smooth saturating nonlinearity of
        // the same nominal scale (c = jointAngleClamp):
        //   angles_[i] = c * tanh(angles_[i] / c)
        // Continuous derivative everywhere, approaches +/-c asymptotically,
        // reduces to ~identity for |angle| << c (small healthy bends
        // essentially unaffected). A much larger true hard safety ceiling
        // (1.2 rad - the exact value this project's own history says caused
        // catastrophic "tiny knot" curling when IT was the primary clamp,
        // see jointAngleClamp's comment above) is still applied after this,
        // purely as a numerical backstop, not the primary limiter. 0.0
        // (default) = off, bitwise-identical to today's shipped hard clamp.
        // >0.0 = on. See WORM_V5_SOFT_JOINT_RESISTANCE_RESULTS.md for
        // whether this actually removes the "pins with zero variance"
        // pathology and produces a smoother whole-body bending shape - NOT
        // shipped as the default in that pass, measurement only.
        std::atomic<float> jointSoftSaturation{0.0f};

        // WormBody::joint_stiffening_gain_ (see body.hpp::
        // set_joint_stiffening_gain, body.cpp WormBody::step) - a second,
        // physically distinct alternative to jointAngleClamp's hard wall,
        // closer to the project owner's proposal read literally ("resists
        // turning" rather than "limits it"): a cubic (Duffing-oscillator
        // -style) softening-spring restoring term added to the angle
        // accumulation BEFORE any clamp/saturation:
        //   angles_[i] += -k_soft * angles_[i]^3 * dt
        // Negligible near zero, growing rapidly as |angle| grows - the
        // equilibrium is wherever this resistance balances the network's own
        // drive, not an externally imposed ceiling. When active (k_soft>0)
        // WITHOUT jointSoftSaturation also enabled, the small jointAngleClamp
        // hard wall is bypassed entirely (see body.cpp) - only the same
        // large 1.2 rad safety net applies, since the whole point is to let
        // k_soft vs. drive set the equilibrium, not have it re-pinned
        // against the old ±0.25 rad literal immediately after.
        //
        // SHIPPED (0.0 -> 4.0, see WORM_V5_SOFT_JOINT_RESISTANCE_RESULTS.md,
        // by the project owner's own direct request/proposal - "resists
        // turning instead of strictly limiting it"). Of the two mechanisms
        // tried, tanh (jointSoftSaturation) was a clean negative - it
        // collapsed the whole-body shape into one dominant hump (bend-zone
        // count -63% to -81%), independently confirmed on two fresh seeds -
        // stays off. k_soft=4.0 is the honest choice: peak per-joint
        // amplitude reaches 81.0-96.6% of the real-biology target
        // (0.494-0.589 rad, WORM_V5_REAL_AMPLITUDE_TARGET.md) - the closest
        // this whole session has gotten - path efficiency IMPROVES 6.4-11.4%
        // over the hard clamp (not just a smaller loss), and SURVIVAL held
        // 48/48 on both media across all 240 independently-tested
        // (config x base x medium) combinations on a fresh seed, zero
        // exceptions, worst-case minCoiledRatio margin 2.23x the failure
        // threshold. HONEST CAVEAT (independent verification's own finding,
        // not smoothed over): the narrower claim that k_soft actively
        // IMPROVES bend-zone count above the hard clamp did NOT reproduce on
        // two independent fresh seeds - it sits at roughly the SAME zone
        // count as the hard clamp (does not collapse it the way tanh does,
        // rather than actively improving on it). The specific "only two
        // bending zones" live-demo observation that motivated this whole
        // investigation was also not literally reproduced in the measured
        // sustained-window statistic (~3.4-3.5 zones for both the hard clamp
        // and k_soft=4.0 on the tested seeds) - an open, unresolved
        // discrepancy between the live visual and this batch measurement,
        // not swept under the rug.
        // ВОЗВРАТ К 0.0 - ВЫКЛЮЧЕНО (WORM_V5_SPATIAL_ENVELOPE_DIAGNOSIS.md).
        // 4.0 было отгружено против прямой рекомендации собственного отчёта
        // (WORM_V5_SOFT_JOINT_RESISTANCE_RESULTS.md: "НЕ готово к отгрузке в
        // дефолт"), по метрике пиковой амплитуды одного сустава, которая, как
        // показал диагноз, не отражает форму тела вообще. На исправленной
        // конфигурации включение кубической жёсткости ДАЁТ биологическую
        // пиковую амплитуду (0.574 против 0.250 рад), но роняет огибающую:
        // coverage 0.916 -> 0.547, endRatio 0.659 -> 0.387 (16 баз x 4 сида,
        // свежий baseSeed=5517293). То есть размен "амплитуда против
        // волны по всему телу" - реальный и НЕ решён; выбран вариант с волной
        // по всему телу, потому что именно её отсутствие было видно глазами.
        // Механизм остаётся на месте и включается одним значением.
        std::atomic<float> jointStiffeningGain{0.0f};

        // WormBody::drag_adhesion_gain_ (см. body.hpp::set_drag_adhesion_gain,
        // body.cpp::solve_propulsion) - единственная в проекте попытка
        // честно тронуть САМ ЗАКОН СИЛЫ трения, а не гейн/темп нейронного
        // привода поверх него (все пять таких попыток - см. WORM.md раздел
        // 6 - провалились одинаково). Обоснование: агар физически НЕ
        // описывается чистым линейным RFT (сила ~ скорость с фиксированным
        // c_n) - Rabets, Backholm, Dalnoki-Veress & Ryu 2014 (Biophysical J.
        // 107:1980) прямыми измерениями нашли, что вязкоупругость геля даёт
        // НЕПОСТОЯННЫЕ коэффициенты трения (червь проседает в бороздку и
        // прилипает - капиллярность + пластичность), не захваченные
        // исходной RFT; Sauvage et al. 2011 (elasto-hydrodynamical model)
        // независимо предлагают смесь капиллярного прилипания + смазочной
        // гидродинамики + упругости геля/тела - качественно другой закон
        // силы, не просто больший коэффициент. Реализация: c_n
        // пер-сегментно домножается на max(0, 1 + gain*|u_k|), где u_k -
        // скорость центра сегмента ТОЛЬКО от смены формы (уже известна до
        // решения системы баланса сил - см. solve_propulsion), НЕ полная
        // скорость с учётом искомых (Vx,Vy,w) - иначе система перестала бы
        // быть линейной и потребовала итераций вместо честного Крамера.
        // Знак НЕ предсказывается литературой напрямую в терминах этой
        // конкретной параметризации (капиллярное прилипание - это
        // сопротивление, растущее с усилием, то есть скорее gain>0; плёнка
        // смазки - обратный эффект, скорее gain<0) - определяется поиском,
        // как и остальные параметры этой сессии без прямой цитаты на знак
        // (cpgAmpLoadSensitivity и т.п.). 0.0 = выключено, побитово прежняя
        // чисто линейная RFT-физика - см. tests/worm_drag_adhesion_
        // calibration за статусом калибровки.
        // WormBody::drag_settle_gain_/drag_settle_tau_ (body.hpp::
        // set_drag_settle, body.cpp) - ЗАМЕНА трёх мгновенных adhesion-
        // формул v1 (мультипликативной/аддитивной/насыщающейся - все три
        // задокументированы и удалены, см. WORM.md раздел 6 и
        // WORM_V2_DESIGN.md раздел 4 за полным разбором). Все три были
        // МГНОВЕННЫМИ (алгебраическими) функциями одной и той же
        // кинематической величины |u_k| в тот же момент времени - формально
        // разные, но математически ВСЕ сошлись к одному и тому же потолку
        // water/agar~=1.0-1.02 при больших коэффициентах: большая добавка
        // одинаково "стирает" базовую анизотропию c_n что у агара (40), что
        // у воды (1.7), потому что величина добавки НЕ ЗАВИСИТ от того, что
        // произошло раньше во времени - только от текущего кадра. Это
        // доказанное структурное свойство ВСЕГО класса "мгновенная функция
        // от |u_k|", не совпадение отдельных неудачных чисел.
        //
        // Реальная агаровая вязкоупругость (Rabets, Backholm, Dalnoki-Veress
        // & Ryu 2014, Biophysical J. 107:1980 - secondhand, полный текст был
        // недоступен, честно помечено как ниже уверенности; Sauvage et al.
        // 2011, elasto-hydrodynamical model) описывается КАЧЕСТВЕННО иначе:
        // червь физически проседает в бороздку геля с конечной временной
        // постоянной (~1-3с) - сопротивление в момент t зависит от того,
        // СКОЛЬКО времени тело уже давит на это место, не только от того, с
        // какой скоростью оно давит ПРЯМО СЕЙЧАС. Это ПАМЯТЬ (state), а не
        // мгновенная функция - и именно поэтому три предыдущих мгновенных
        // формулы не могли, в принципе, её воспроизвести, вне зависимости от
        // параметризации. WormBody::penetration_depth_ - новое персистентное
        // состояние (по сегменту), релаксирующее к нормированной нагрузке
        // ПРОШЛОГО шага (Kelvin-Voigt-style, alpha=dt/tau) - см. body.cpp за
        // точными уравнениями. c_n получает ОДИН аддитивный член:
        //   cnk[k] = cn + dragSettleGain * penetration_depth_[k]
        // Решение баланса сил остаётся ЛИНЕЙНЫМ (penetration_depth_ уже
        // известен из прошлого шага к моменту решения этого) - тот же
        // паттерн, что и у всех остальных load-based каналов в этом проекте.
        //
        // dragSettleTau=2.0с - середина честного (но secondhand) диапазона
        // Rabets 2014 (~1-3с). dragSettleGain - НЕ выводится ни из одного
        // источника (Rabets не даёт жёсткость контакта, платный полный текст
        // недоступен) - честно открытый параметр, найден экраном+16-базовым
        // подтверждением (см. WORM_V2_RESULTS.md), не выведен аналитически.
        //
        // ПЕРЕСМОТРЕНО (0.0 -> 20.0 -> 25.0): на новой (muscleCalciumTau=0.1/
        // bodyPoseDecayRate=0.6) точке экран нашёл, что скорость растёт
        // монотонно с gain, здоровье держится 4/4 (малый скрин) до gain=35 -
        // но 16-базовое подтверждение поймало проклятие победителя именно на
        // 35 (13/16 агар, 10/16 вода на широкой выборке против 4/4 на узком
        // скрине). Сначала отступили до 20 - надёжно держало 15/16 на ОБЕИХ
        // средах на 16 базах (не 16/16 - одна и та же повторяющаяся
        // пограничная база, эффективность впритык к порогу 0.40,
