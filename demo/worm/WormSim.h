        // Мышечный (Output) leak - см. Network::set_muscle_leak. v1 держала
        // это на 0.0 (leak Output-нейронов архитектурно заперт на 0 - см.
        // network.cpp) - единственная историческая изолированная попытка
        // дать ему обычный ненулевой leak подняла частоту сети в 3-4 раза,
        // но обвалила эффективность ползания в ~28 раз (тело физически не
        // успевало превращать более быстрый нейронный сигнал в согласованную
